"""Frozen NSL graph-loss oracle for lance-graph-nsl.

Runs the UNMODIFIED `neural_structured_learning.lib.distances.
pairwise_distance_wrapper` (with `configs.DistanceConfig`) over seeded inputs
and writes inputs and TensorFlow's f32 result to ../data/nsl_loss_golden.txt.
Inputs are generated here once, so both sides read identical f32 bits.

Usage:
    python nsl_loss_oracle.py <path-to-neural-structured-learning-checkout>

Only configs/ and lib/distances.py execute; the package __init__ (Keras) and
lib/__init__ are bypassed with empty package shells.
"""
import hashlib
import os
import struct
import sys
import types

import numpy as np

NSL_ROOT = os.path.abspath(sys.argv[1])
HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")
PKG = os.path.join(NSL_ROOT, "neural_structured_learning")
for name, sub in (("neural_structured_learning", ""), ("neural_structured_learning.lib", "lib")):
    mod = types.ModuleType(name)
    mod.__path__ = [os.path.join(PKG, sub)]
    sys.modules[name] = mod

import tensorflow as tf  # noqa: E402
import neural_structured_learning.configs as configs  # noqa: E402
from neural_structured_learning.lib import distances  # noqa: E402

R = tf.compat.v1.losses.Reduction


def hx(v):
    return struct.pack("<f", float(v))[::-1].hex()


def sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def loss(src, tgt, w, dist, axis, reduction, transform="none"):
    cfg = configs.DistanceConfig(distance_type=dist, reduction=reduction, sum_over_axis=axis,
                                 transform_fn=transform)
    out = distances.pairwise_distance_wrapper(
        tf.constant(src, tf.float32), tf.constant(tgt, tf.float32),
        weights=tf.constant(w.reshape(-1, 1), tf.float32), distance_config=cfg)
    return np.float32(out.numpy())


def cases():
    rs = np.random.RandomState(20261028)
    n = 16

    def pair(d, noise):
        s = rs.normal(0, 1, (n, d)).astype(np.float32)
        return s, (s + rs.normal(0, noise, (n, d))).astype(np.float32)

    def weights(zero_half=False):
        w = rs.uniform(0.5, 1.0, n).astype(np.float32)
        if zero_half:
            w[::2] = 0.0
        return w

    for d in (4, 32, 128):
        s, t = pair(d, 0.5)
        yield "l2_d%d" % d, s, t, weights(), "l2", None, R.SUM_BY_NONZERO_WEIGHTS
    s, t = pair(32, 0.5)
    yield "l2_axis_d32", s, t, weights(), "l2", -1, R.SUM_BY_NONZERO_WEIGHTS
    s, t = pair(32, 0.5)
    yield "l1_d32", s, t, weights(), "l1", None, R.SUM_BY_NONZERO_WEIGHTS
    s, t = pair(32, 0.5)
    yield "cos_axis_d32", s, t, weights(), "cosine", -1, R.SUM_BY_NONZERO_WEIGHTS
    s, t = pair(32, 1e-3)
    yield "l2_neardup_d32", s, t, weights(), "l2", None, R.SUM_BY_NONZERO_WEIGHTS
    s, t = pair(32, 0.5)
    s[:, 0] *= 100.0
    t[:, 0] *= 100.0
    yield "l2_outlier_d32", s, t, weights(), "l2", None, R.SUM_BY_NONZERO_WEIGHTS
    s, t = pair(32, 0.5)
    yield "l2_zerow_d32", s, t, weights(zero_half=True), "l2", None, R.SUM_BY_NONZERO_WEIGHTS
    # 00a toy: h = tanh(x @ I + 0); pairs A->C (0.9), B->C (0.4) after max_nbrs=1.
    feats = {"A": [1.0, 0.0], "B": [0.0, 1.0], "C": [1.0, 1.0]}
    h = {k: np.tanh(np.float32(v)).astype(np.float32) for k, v in feats.items()}
    s = np.stack([h["A"], h["B"]]).astype(np.float32)
    t = np.stack([h["C"], h["C"]]).astype(np.float32)
    yield "toy_00a", s, t, np.array([0.9, 0.4], np.float32), "l2", None, R.SUM_BY_NONZERO_WEIGHTS
    # Appended (keeps the stream for the cases above): softmax-transformed
    # divergences on 10-class logits, transform_fn=SOFTMAX along the last axis.
    for dist in ("kl_divergence", "jensen_shannon_divergence"):
        for noise in (0.5, 0.1, 0.01):
            s = (2.0 * rs.normal(0, 1, (n, 10))).astype(np.float32)
            t = (s + rs.normal(0, noise, (n, 10))).astype(np.float32)
            tag = "kl" if dist == "kl_divergence" else "js"
            yield "%s_softmax_n%s" % (tag, str(noise).replace(".", "p")), s, t, weights(), dist, -1, R.SUM_BY_NONZERO_WEIGHTS


def main():
    lines = [
        "# generated by oracle/nsl_loss_oracle.py; do not edit",
        "# tensorflow %s, numpy %s, python %s" % (tf.__version__, np.__version__, sys.version.split()[0]),
        "# sha256 lib/distances.py %s" % sha256(os.path.join(PKG, "lib", "distances.py")),
        "# sha256 configs/configs.py %s" % sha256(os.path.join(PKG, "configs", "configs.py")),
        "# case <name> <distance> <axis none|-1> <reduction> <pairs> <dim>; then src/tgt rows, w, tf",
    ]
    count = 0
    for name, s, t, w, dist, axis, red in cases():
        transform = "softmax" if dist in ("kl_divergence", "jensen_shannon_divergence") else "none"
        lines.append("case %s %s %s %s %d %d" % (name, dist, "none" if axis is None else axis, red, s.shape[0], s.shape[1]))
        lines += ["src " + " ".join(hx(v) for v in row) for row in s]
        lines += ["tgt " + " ".join(hx(v) for v in row) for row in t]
        lines.append("w " + " ".join(hx(v) for v in w))
        lines.append("tf " + hx(loss(s, t, w, dist, axis, red, transform)))
        lines.append("end")
        count += 1
    with open(os.path.join(DATA, "nsl_loss_golden.txt"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("cases %d" % count)


if __name__ == "__main__":
    main()
