"""Frozen NSL oracle for the lance-graph-nsl neighbor fixtures.

Runs the UNMODIFIED `neural_structured_learning.tools.pack_nbrs.pack_nbrs`
(and through it `graph_utils.read_tsv_graph` / `add_undirected_edges`) over
every fixture in ../data/fixtures.txt, end to end: TFRecord in, TSV graph in,
TFRecord out. It parses the packed output and writes ../data/nsl_golden.txt.

Usage:
    python nsl_pack_oracle.py <path-to-neural-structured-learning-checkout>

The package's own __init__ imports Keras; this script registers empty package
shells so that only tools/graph_utils.py and tools/pack_nbrs.py execute, both
unmodified. Their SHA-256 values are written into the golden header.
"""
import hashlib
import os
import struct
import sys
import tempfile
import types

NSL_ROOT = os.path.abspath(sys.argv[1])
HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")

for name, sub in (("neural_structured_learning", ""), ("neural_structured_learning.tools", "tools")):
    mod = types.ModuleType(name)
    mod.__path__ = [os.path.join(NSL_ROOT, "neural_structured_learning", sub)]
    sys.modules[name] = mod

import tensorflow as tf  # noqa: E402
from neural_structured_learning.tools import pack_nbrs as nsl_pack  # noqa: E402


def f32_hex(v):
    return struct.pack("<f", v)[::-1].hex()


def sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def parse_fixtures(path):
    fixtures, cur = [], None
    for raw in open(path):
        line = raw.rstrip("\n")
        if not line or line.startswith("#"):
            continue
        tok = line.split(" ")
        if tok[0] == "fixture":
            opts = dict(t.split("=") for t in tok[2:])
            cur = {"id": tok[1], "cap": opts["cap"], "undirected": opts["undirected"] == "1",
                   "seeds": [], "unlabeled": [], "edges": []}
        elif tok[0] in ("seed", "unlabeled"):
            cur["seeds" if tok[0] == "seed" else "unlabeled"].append((tok[1], tok[2], float(tok[3])))
        elif tok[0] == "edge":
            cur["edges"].append(tok[1:])
        elif tok[0] == "end":
            fixtures.append(cur)
            cur = None
        else:
            raise ValueError("bad line: " + line)
    return fixtures


def example(node_id, tag, x):
    ex = tf.train.Example()
    ex.features.feature["id"].bytes_list.value.append(node_id.encode())
    ex.features.feature["tag"].bytes_list.value.append(tag.encode())
    ex.features.feature["x"].float_list.value.append(x)
    return ex


def write_records(path, rows):
    with tf.io.TFRecordWriter(path) as w:
        for row in rows:
            w.write(example(*row).SerializeToString())


def run(fx, tmp):
    lab = os.path.join(tmp, fx["id"] + "-lab.tfr")
    unl = os.path.join(tmp, fx["id"] + "-unl.tfr")
    tsv = os.path.join(tmp, fx["id"] + ".tsv")
    out = os.path.join(tmp, fx["id"] + "-out.tfr")
    write_records(lab, fx["seeds"])
    if fx["unlabeled"]:
        write_records(unl, fx["unlabeled"])
    with open(tsv, "w") as f:
        for e in fx["edges"]:
            f.write("\t".join(e) + "\n")
    cap = None if fx["cap"] == "none" else int(fx["cap"])
    nsl_pack.pack_nbrs(lab, unl if fx["unlabeled"] else "", tsv, out,
                       add_undirected_edges=fx["undirected"], max_nbrs=cap)
    lines = []
    for raw in tf.data.TFRecordDataset([out]):
        ex = tf.train.Example()
        ex.ParseFromString(raw.numpy())
        feat = ex.features.feature
        seed = feat["id"].bytes_list.value[0].decode()
        n = feat["NL_num_nbrs"].int64_list.value[0]
        keys = ",".join(sorted(feat.keys()))
        lines.append("seed %s %s %d %s" % (fx["id"], seed, n, keys))
        for i in range(n):
            p = "NL_nbr_%d_" % i
            lines.append("nbr %s %s %d %s %s %s %s" % (
                fx["id"], seed, i,
                feat[p + "id"].bytes_list.value[0].decode(),
                f32_hex(feat[p + "weight"].float_list.value[0]),
                feat[p + "tag"].bytes_list.value[0].decode(),
                f32_hex(feat[p + "x"].float_list.value[0])))
    return lines


def main():
    fixtures = parse_fixtures(os.path.join(DATA, "fixtures.txt"))
    tools = os.path.join(NSL_ROOT, "neural_structured_learning", "tools")
    header = [
        "# generated by oracle/nsl_pack_oracle.py; do not edit",
        "# tensorflow %s, python %s" % (tf.__version__, sys.version.split()[0]),
        "# sha256 graph_utils.py %s" % sha256(os.path.join(tools, "graph_utils.py")),
        "# sha256 pack_nbrs.py %s" % sha256(os.path.join(tools, "pack_nbrs.py")),
        "# sha256 fixtures.txt %s" % sha256(os.path.join(DATA, "fixtures.txt")),
        "# seed <fixture> <seed> <num_nbrs> <sorted feature keys>",
        "# nbr <fixture> <seed> <index> <nbr id> <weight f32 hex> <tag> <x f32 hex>",
    ]
    body = []
    with tempfile.TemporaryDirectory() as tmp:
        for fx in fixtures:
            body += run(fx, tmp)
    with open(os.path.join(DATA, "nsl_golden.txt"), "w") as f:
        f.write("\n".join(header + body) + "\n")
    print("fixtures %d, lines %d" % (len(fixtures), len(body)))


if __name__ == "__main__":
    main()
