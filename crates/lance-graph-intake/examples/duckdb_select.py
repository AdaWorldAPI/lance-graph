"""D-INTAKE-2D: DuckDB's side of the selection benchmark.

Same data as lance-graph-intake/examples/select_bench.rs, generated by the
same formulas: row r has id = r + 1, a = (r * 7919) % 1000, b = NULL when
r % 5 == 0 else (r * 31) % 50 - 25, t = 'v' || ((r * 13) % 40).

Predicates:
  P1: a < 100                       (10 % of rows)
  P2: a < 100 AND b >= 0            (three-valued: NULL b drops the row)
  P3: id IN (a bag of 4096 keys)    (key bag, list order is not kept by SQL)

Reported per predicate, in nanoseconds:
  cold: the first COUNT(*) on a fresh connection;
  warm: median of 11 further COUNT(*) runs (DuckDB recomputes each time);
  ids:  median of 11 runs fetching the selected ids as a numpy array.
"""
import json
import statistics
import sys
import time

import duckdb


def run(n: int) -> dict:
    con = duckdb.connect()
    con.execute(
        f"""CREATE TABLE t AS SELECT
            (r + 1)::INTEGER AS id,
            ((r * 7919) % 1000)::INTEGER AS a,
            CASE WHEN r % 5 = 0 THEN NULL ELSE ((r * 31) % 50 - 25)::INTEGER END AS b,
            'v' || ((r * 13) % 40)::VARCHAR AS t
          FROM range({n}) tbl(r)"""
    )
    keys = ",".join(str(1 + (k * 2654435761) % n) for k in range(4096))
    preds = {
        "P1": "a < 100",
        "P2": "a < 100 AND b >= 0",
        "P3": f"id IN ({keys})",
    }
    out = {}
    for name, p in preds.items():
        q = f"SELECT count(*) FROM t WHERE {p}"
        t0 = time.perf_counter_ns()
        count = con.execute(q).fetchone()[0]
        cold = time.perf_counter_ns() - t0
        warm = []
        for _ in range(11):
            t0 = time.perf_counter_ns()
            con.execute(q).fetchone()
            warm.append(time.perf_counter_ns() - t0)
        ids = []
        for _ in range(11):
            t0 = time.perf_counter_ns()
            con.execute(f"SELECT id FROM t WHERE {p}").fetchnumpy()
            ids.append(time.perf_counter_ns() - t0)
        out[name] = {
            "selected": count,
            "cold_ns": cold,
            "warm_ns": statistics.median(warm),
            "ids_ns": statistics.median(ids),
            "warm_ns_per_selected": statistics.median(warm) / max(count, 1),
        }
    return out


if __name__ == "__main__":
    sizes = [int(s) for s in sys.argv[1:]] or [100_000, 1_000_000]
    print(json.dumps({str(n): run(n) for n in sizes}, indent=1))
