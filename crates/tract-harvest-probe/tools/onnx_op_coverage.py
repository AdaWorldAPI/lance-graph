#!/usr/bin/env python3
"""ONNX default-domain op coverage across runtimes -> data/onnx_op_coverage.tsv.

Every column is read from the runtime's own registry or source, never typed:

- onnx:   onnx.defs.get_all_schemas() (the 203 default-domain ops of onnx 1.23.2)
- tract:  `reg.insert("<Op>", ...)` in Tract's onnx/src (the checkout Cargo.lock names)
- ort:    onnxruntime CPU kernel defs (get_all_opkernel_def, CPUExecutionProvider)
- burn:   onnx-ir NodeType variants registered in ProcessorRegistry and not mapped
          to `unsupported::`, matched to ONNX names case-insensitively (as strum
          does), with burn's rank-split variants (Conv1d/2d/3d, MaxPool1d, ...)
          folded back to their ONNX op. Parse/IR support; burn-onnx codegen is
          per IR node and not cross-checked per op here.
- candle: the top-level `match node.op_type.as_str()` arms of candle-onnx eval.rs
- probe:  op types registered in this crate's registry (src/registry.rs reg! rows
          and src/generated.rs draft rows)

usage:
    python3 tools/onnx_op_coverage.py <tract onnx/src dir> <onnx-ir src dir> <candle-onnx eval.rs>

Registered by name is not full support: attributes, dtypes and opset ranges
are not compared.
"""
import os
import re
import sys

import onnx
import onnx.defs
import onnxruntime as ort
from onnxruntime.capi import onnxruntime_pybind11_state as C

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read(p):
    with open(p) as f:
        return f.read()


def tract_ops(src_dir):
    ops = set()
    for root, _, files in os.walk(src_dir):
        for f in files:
            if f.endswith(".rs"):
                ops |= set(re.findall(r'reg\.insert\("([A-Za-z0-9_]+)"', read(os.path.join(root, f))))
    return ops


def burn_ops(ir_src, onnx_names):
    reg = read(os.path.join(ir_src, "registry.rs"))
    node = read(os.path.join(ir_src, "ir", "node.rs"))
    registered = set(re.findall(r"registry\.register\(\s*NodeType::(\w+)", reg))
    variant_mod = dict(re.findall(r"^\s+(\w+)\s*=>\s*([\w:]+)", node, re.M))
    low = {o.lower(): o for o in onnx_names}
    out = set()
    for v in registered:
        if v == "Custom" or variant_mod.get(v, "").startswith("unsupported"):
            continue
        for cand in (v, re.sub(r"[123]d$", "", v)):
            if cand.lower() in low:
                out.add(low[cand.lower()])
                break
    return out


def candle_ops(eval_rs):
    src = read(eval_rs)
    start = src.index("match node.op_type.as_str() {")
    end = src.index("op_type => bail!", start)
    return set(re.findall(r'^\s{12}"([A-Za-z0-9_]+)"', src[start:end], re.M))


def probe_ops():
    ops = set(re.findall(r'reg!\(\s*"[^"]*",\s*"([A-Za-z0-9_]+)"', read(os.path.join(HERE, "src", "registry.rs"))))
    ops |= set(re.findall(r'draft\(\s*"[^"]*",\s*"([A-Za-z0-9_]+)"', read(os.path.join(HERE, "src", "generated.rs"))))
    return ops


def main():
    tract_dir, ir_dir, candle_eval = sys.argv[1:4]
    onnx_names = sorted({s.name for s in onnx.defs.get_all_schemas() if s.domain in ("", "ai.onnx")})
    cols = {
        "tract": tract_ops(tract_dir),
        "ort": {k.op_name for k in C.get_all_opkernel_def()
                if (k.domain or "ai.onnx") == "ai.onnx" and k.provider == "CPUExecutionProvider"},
        "burn": burn_ops(ir_dir, onnx_names),
        "candle": candle_ops(candle_eval),
        "probe": probe_ops(),
    }
    out = os.path.join(HERE, "data", "onnx_op_coverage.tsv")
    with open(out, "w") as f:
        f.write("# ONNX default-domain op coverage. Generated by tools/onnx_op_coverage.py; do not edit.\n")
        f.write(f"# onnx {onnx.__version__}, onnxruntime {ort.__version__} (CPU kernels), tract {os.path.basename(os.path.dirname(os.path.dirname(tract_dir.rstrip('/'))))}, "
                f"burn {os.path.basename(os.path.dirname(ir_dir.rstrip('/')))}, candle {os.path.basename(os.path.dirname(os.path.dirname(candle_eval)))}\n")
        f.write("# 1 = registered by name. Registered is not full support (attributes, dtypes, opsets not compared).\n")
        f.write("op\t" + "\t".join(cols) + "\n")
        for op in onnx_names:
            f.write(op + "\t" + "\t".join("1" if op in s else "0" for s in cols.values()) + "\n")
        f.write("# totals\t" + "\t".join(str(len(s & set(onnx_names))) for s in cols.values()) + "\n")
    print({k: len(s & set(onnx_names)) for k, s in cols.items()}, "of", len(onnx_names))


if __name__ == "__main__":
    main()
