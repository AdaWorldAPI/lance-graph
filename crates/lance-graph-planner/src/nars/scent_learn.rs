    /// The table equals TFLite Micro's `LUTPopulateInt8` on every int8 code:
    /// `table[v]` for `v >= 0`, `-table[-v]` for `v < 0` (oddness).
    #[test]
    fn the_step_table_matches_tflm_on_every_int8_code() {
        let golden = include_str!("data/tflm_lut_step_golden.txt");
        let mut rows = 0;
        for line in golden.lines() {
            let f: Vec<i32> = line
                .split(' ')
                .skip(1)
                .map(|t| t.parse().unwrap())
                .collect();
            let (num, den, v, tflm) = (f[0] as u8, f[1] as u8, f[2], f[3]);
            let t = prepare(UpdateRule::Symmetric(Rate { num, den })).unwrap();
            let ours = if v >= 0 {
                i32::from(t.table()[v as usize])
            } else {
                -i32::from(t.table()[(-v) as usize])
            };
            assert_eq!(ours, tflm, "rate {num}/{den}, code {v}");
            rows += 1;
        }
        assert_eq!(rows, 4 * 256);
    }

    fn lane_of(code: u16) -> EpiLane9 {
        EpiLane9::from_codeword(code).unwrap()
    }

    fn step_one(step: &PreparedStep, lane: EpiLane9) -> EpiLane9 {
        let (mut out, mut out_p) = ([0u8; 1], [0u64; 1]);
        lut9(
            &[lane.magnitude()],
            &[u64::from(lane.presence())],
            step.table(),
            &mut out,
            &mut out_p,
        );
        lane_of(u16::from(out[0]) | ((out_p[0] & 1) as u16) << 8)
    }

    /// PZ1. Every one of the 512 codewords through the prepared step equals
    /// an independent f64 oracle: `sign(v)·round_away(|v|·η)`, zero as `+0`,
    /// `NEVER_TOUCHED` unchanged.
    #[test]
    fn pz1_the_step_matches_a_scalar_oracle_on_every_codeword() {
        for rate in RATES {
            let step = prepare(UpdateRule::Symmetric(rate)).unwrap();
            let eta = f64::from(rate.num) / f64::from(rate.den);
            for code in 0..512u16 {
                let lane = lane_of(code);
                let got = step_one(&step, lane);
                let want = match lane.value() {
                    None => EpiLane9::NEVER_TOUCHED,
                    Some(v) => {
                        let m = (f64::from(v.unsigned_abs()) * eta).round() as u8;
                        let positive = v >= 0 || m == 0;
                        lane_of(u16::from(m) | u16::from(positive) << 8)
                    }
                };
                assert_eq!(got, want, "rate {rate:?}, code {code:#x}");
            }
        }
    }

    /// PZ2. A touched negative step that comes out of the rate table as 0
    /// is `+0`, not "never touched"; an untouched input stays untouched.
    #[test]
    fn pz2_a_negative_step_to_zero_is_touched_plus_zero() {
        assert_eq!(lane(0), lane_of(0x100));
        assert!(!lane(0).never_touched());
        let step = prepare(UpdateRule::Symmetric(QUARTER)).unwrap();
        let minus_one = lane(-1);
        let out = step_one(&step, minus_one);
        assert!(
            !out.never_touched(),
            "-1 · 1/4 is 0 in the table but the lane was touched"
        );
        assert_eq!(out.value(), Some(0));
        assert!(step_one(&step, EpiLane9::NEVER_TOUCHED).never_touched());
    }

    /// PZ2 in the learner: −0.49 → −0 → +0. A present feature whose delta
    /// truncates to zero is marked seen (`+0`), not left "never touched".
    /// x = 1, so |delta| = 127/255 ≈ 0.498 truncates to 0. The residual is
    /// negative, so only the zero rule (`M == 0`) can set P; a positive
    /// residual would set it through the sign alone.
    #[test]
    fn pz2_a_negative_delta_truncating_to_zero_is_marked_seen() {
        let step = prepare(UpdateRule::Symmetric(HALF)).unwrap();
        let mut l = ScentLearner::new(step.spec());
        let mut lead = fixed_lead(0.9, 0.8);
        lead.uncertainty = 0.002;
        assert_eq!(features(&lead)[3], 1, "fixture must give x = 1");
        assert_eq!(
            l.learn(&step, &lead, Outcome::Refuted, 1),
            Ok(Learned::Updated { residual: -127 })
        );
        assert_eq!(l.weights()[3], lane(0));
        assert!(!l.weights()[3].never_touched());
    }

