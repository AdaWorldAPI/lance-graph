    /// The whole update against an independent f64 implementation.
    #[test]
    fn pz1_the_update_matches_a_scalar_oracle() {
        let step = prepare(UpdateRule::Symmetric(Rate { num: 3, den: 4 })).unwrap();
        let mut l = ScentLearner::new(step.spec());
        let mut w = [None::<i32>; FEATURES];
        let script = [
            (fixed_lead(0.9, 0.8), Outcome::Hydrated),
            (fixed_lead(0.3, 0.7), Outcome::Refuted),
            (fixed_lead(0.6, 0.9), Outcome::Refuted),
            (fixed_lead(0.95, 0.6), Outcome::Hydrated),
            (fixed_lead(0.2, 0.6), Outcome::Refuted),
        ];
        for (src, (lead, outcome)) in script.iter().enumerate() {
            let x = features(lead);
            let score: i64 = x
                .iter()
                .zip(&w)
                .map(|(&xi, wi)| i64::from(wi.unwrap_or(0)) * i64::from(xi))
                .sum();
            let p = (score / i64::from(SCORE_SCALE)).clamp(-127, 127);
            let t = if *outcome == Outcome::Hydrated {
                127
            } else {
                -127
            };
            let r = t - p;
            for i in 0..FEATURES {
                if x[i] == 0 {
                    continue;
                }
                // Truncation toward zero, as an independent f64 formula.
                let d = (r as f64 * f64::from(x[i]) / 255.0).trunc();
                let s = d.signum() * (d.abs() * 0.75).round();
                w[i] = Some((w[i].unwrap_or(0) + s as i32).clamp(-255, 255));
            }
            l.learn(&step, lead, *outcome, src as u32).unwrap();
            let got: Vec<Option<i32>> = l
                .weights()
                .iter()
                .map(|e| e.value().map(i32::from))
                .collect();
            assert_eq!(got, w.to_vec(), "after step {src}");
        }
    }

