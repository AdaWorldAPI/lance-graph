//! `scent_learn`: a learned ordering of C3b scent leads (D-EPI-COT C3c).
//!
//! [`super::scent::scent`] ranks candidate mediators by status, then by
//! uncertainty. Leads with the same status and uncertainty are ordered by
//! mediator id, which carries no information. [`ScentLearner`] learns from
//! investigation outcomes which leads in a status group are worth testing
//! first.
//!
//! # What it is and is not
//!
//! - It reorders leads **within** a C3b status group and never across one.
//!   A contested lead (a mature link with contradicting evidence) therefore
//!   still comes before a settled one, however the weights move (PZ8).
//! - Its output is an order. It never writes truth, Epi5 bits, CE64 bits or
//!   the ledger, and a prediction is never recorded as an observation (PZ4).
//! - One outcome source trains it once; a replay is refused (PZ6).
//!
//! # Numerics
//!
//! The arithmetic consumes merged ndarray kernels and adds none:
//!
//! - Weights and steps are [`EpiLane9`] (Codec9 / DR512 sign-magnitude).
//!   `NEVER_TOUCHED` (P=0, M=0) means "feature never seen", distinct from a
//!   learned `+0`.
//! - **Nothing at runtime rounds or roundtrips through a float.** A delta is
//!   built in code space: magnitude `|r|·x / 255` by integer truncation (odd,
//!   deterministic), sign from `r`. A touched delta whose magnitude truncates
//!   to 0 gets P=1 by a mask rule, `P = present AND (positive OR M == 0)`, so
//!   −0.49 becomes +0, never "never touched" (PZ2). This is the same zero rule
//!   `lut9` applies to its own output. Weights are added and saturated as
//!   integers.
//! - The learning rate is applied by `ndarray::simd::lut9`, a plain
//!   table lookup that only evaluates odd functions. Only a symmetric rule is
//!   prepared; an asymmetric or biased rule is refused (PZ3).
//! - Rounding happens once, offline, when the table is built. It follows
//!   TFLite Micro's `LUTPopulateInt8` recipe (`common.h`): code → `x·η` →
//!   `TfLiteRound` (ties away from zero) → saturate. `data/tflm_lut_step_golden.txt` was generated by
//!   `docs/research/epistemic-cot/oracles/tflm_lut_step_oracle.cc`, compiled
//!   against tflite-micro. The table matches it on every int8 code
//!   (magnitudes 0..=128). Magnitudes 129..=255 use the same formula but have
//!   no TFLM counterpart.
//! - A prepared table carries the [`ModelSpec`] it was built for. A learner
//!   refuses a table built for a different schema, calibration or rate (PZ7).
//!   The spec is transient and in memory. It is not a generation store and not
//!   the EXO-152 PZL-4/G1 binding.

use std::collections::BTreeSet;

use ndarray::hpc::codec9::EpiLane9;
use ndarray::simd::lut9;

use super::scent::{Lead, LeadStatus, Link};

/// Feature schema version. Changing [`features`] must bump it.
pub const SCHEMA: u16 = 1;
/// Number of features per lead.
pub const FEATURES: usize = 5;
/// `|score| / SCORE_SCALE` is the prediction, clamped to ±127. Policy pin.
pub const SCORE_SCALE: i32 = 512;
/// Target for an outcome: `+TARGET` hydrated, `-TARGET` refuted.
pub const TARGET: i16 = 127;

/// Feature code for 1.0: feature magnitudes are `0..=FEATURE_SCALE`.
pub const FEATURE_SCALE: u8 = 255;

/// A learning rate `num/den` with `0 < num <= den`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Rate {
    /// Numerator.
    pub num: u8,
    /// Denominator.
    pub den: u8,
}

/// What a prepared table and a learner must agree on.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ModelSpec {
    /// Feature schema version ([`SCHEMA`]).
    pub schema: u16,
    /// Feature code for 1.0 ([`FEATURE_SCALE`]).
    pub feature_scale: u8,
    /// The learning rate.
    pub rate: Rate,
}

impl ModelSpec {
    /// The spec for `rate` under the current schema and codec.
    #[must_use]
    pub fn new(rate: Rate) -> Self {
        ModelSpec {
            schema: SCHEMA,
            feature_scale: FEATURE_SCALE,
            rate,
        }
    }
}

/// An update rule offered for preparation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum UpdateRule {
    /// `step = η · residual`: odd, prepared.
    Symmetric(Rate),
    /// Different rates for positive and negative residuals.
    Asymmetric {
        /// Rate for positive residuals.
        gain: Rate,
        /// Rate for negative residuals.
        loss: Rate,
    },
    /// `step = η · residual + bias`.
    Affine {
        /// The rate.
        rate: Rate,
        /// Constant added to every step.
        bias: i8,
    },
}

/// Why nothing was prepared or learned.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LearnRefusal {
    /// The rule is not an odd function, so `lut9` cannot evaluate it.
    NotOdd,
    /// The rate is zero or above one.
    BadRate,
    /// The table was prepared for a different model.
    StaleTable {
        /// The table's spec.
        table: ModelSpec,
        /// The learner's spec.
        model: ModelSpec,
    },
}

/// A rate table bound to the spec it was built for.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PreparedStep {
    spec: ModelSpec,
    table: [u8; 256],
}

impl PreparedStep {
    /// The spec this table was built for.
    #[must_use]
    pub fn spec(&self) -> ModelSpec {
        self.spec
    }

    /// The magnitude table `lut9` reads.
    #[must_use]
    pub fn table(&self) -> &[u8; 256] {
        &self.table
    }
}

/// Build the rate table for `rule`, or refuse a rule `lut9` cannot evaluate.
///
/// # Errors
/// [`LearnRefusal::NotOdd`] for an asymmetric or biased rule;
/// [`LearnRefusal::BadRate`] for a zero rate or one above 1.
pub fn prepare(rule: UpdateRule) -> Result<PreparedStep, LearnRefusal> {
    let rate = match rule {
        UpdateRule::Symmetric(r) => r,
        UpdateRule::Asymmetric { gain, loss } if gain == loss => gain,
        UpdateRule::Affine { rate, bias: 0 } => rate,
        UpdateRule::Asymmetric { .. } | UpdateRule::Affine { .. } => {
            return Err(LearnRefusal::NotOdd)
        }
    };
    if rate.num == 0 || rate.num > rate.den {
        return Err(LearnRefusal::BadRate);
    }
    // TFLM LUTPopulateInt8 at unit scale: transform in f32, TfLiteRound
    // (ties away from zero), saturate. η ≤ 1 keeps every entry in 0..=255.
    let eta = f32::from(rate.num) / f32::from(rate.den);
    let table = core::array::from_fn(|m| (m as f32 * eta).round() as u8);
    Ok(PreparedStep {
        spec: ModelSpec::new(rate),
        table,
    })
}

/// What one investigation found.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Outcome {
    /// The mediator hydrated the edge.
    Hydrated,
    /// The missing link was not there.
    Refuted,
}

/// What a learning call did.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Learned {
    /// Weights moved; the residual was this.
    Updated {
        /// `target − prediction`.
        residual: i16,
    },
    /// The outcome's source already trained this learner; nothing moved.
    Replayed,
}

fn unit(x: f32) -> u8 {
    (x.clamp(0.0, 1.0) * 255.0).round() as u8
}

/// The link a lead is anchored on: in the chain and with evidence. A testable
/// lead has exactly one; a settled or contested lead uses the weaker one.
fn anchor(lead: &Lead) -> Option<&Link> {
    let anchored = |l: &&Link| l.in_chain && l.truth.is_some();
    let conf = |l: &Link| l.truth.map_or(0.0, |t| t.confidence);
    [&lead.first, &lead.second]
        .into_iter()
        .filter(anchored)
        .min_by(|a, b| conf(a).total_cmp(&conf(b)))
}

/// Feature magnitudes of a lead, 0..=255 each. 0 means "absent": the weight
/// is not consulted and not updated.
///
/// | # | feature |
/// |---|---|
/// | 0 | bias (255) |
/// | 1 | anchor confidence |
/// | 2 | anchor frequency |
/// | 3 | uncertainty of the link to investigate |
/// | 4 | links with evidence (0, 127, 254) |
#[must_use]
pub fn features(lead: &Lead) -> [u8; FEATURES] {
    let a = anchor(lead).and_then(|l| l.truth);
    let evidenced = u8::from(lead.first.truth.is_some()) + u8::from(lead.second.truth.is_some());
    [
        255,
        a.map_or(0, |t| unit(t.confidence)),
        a.map_or(0, |t| unit(t.frequency)),
        unit(lead.uncertainty),
        evidenced * 127,
    ]
}

/// A touched lane for `v` in `-255..=255`; zero is `+0`.
fn lane(v: i16) -> EpiLane9 {
    let code = v.unsigned_abs() | u16::from(v >= 0) << 8;
    EpiLane9::from_codeword(code).expect("|v| <= 255")
}

/// Learned ordering of scent leads. In memory, transient.
#[derive(Debug, Clone)]
pub struct ScentLearner {
    spec: ModelSpec,
    weights: [EpiLane9; FEATURES],
    seen: BTreeSet<u32>,
}

impl ScentLearner {
    /// A learner that has seen nothing: every weight is `NEVER_TOUCHED`.
    #[must_use]
    pub fn new(spec: ModelSpec) -> Self {
        ScentLearner {
            spec,
            weights: [EpiLane9::NEVER_TOUCHED; FEATURES],
            seen: BTreeSet::new(),
        }
    }

    /// The learner's spec.
    #[must_use]
    pub fn spec(&self) -> ModelSpec {
        self.spec
    }

    /// The weights.
    #[must_use]
    pub fn weights(&self) -> &[EpiLane9; FEATURES] {
        &self.weights
    }

    /// `Σ wᵢ·xᵢ` over touched weights and present features.
    #[must_use]
    pub fn score(&self, lead: &Lead) -> i32 {
        features(lead)
            .iter()
            .zip(&self.weights)
            .map(|(&x, w)| i32::from(w.value().unwrap_or(0)) * i32::from(x))
            .sum()
    }

    /// The prediction in `-127..=127`.
    #[must_use]
    pub fn predict(&self, lead: &Lead) -> i16 {
        (self.score(lead) / SCORE_SCALE).clamp(-127, 127) as i16
    }

    /// Reorder `leads` (in `scent` order) by score within each status group.
    /// Equal scores keep the `scent` order; groups keep the `scent` order.
    #[must_use]
    pub fn rank(&self, leads: &[Lead]) -> Vec<Lead> {
        let group = |s: LeadStatus| match s {
            LeadStatus::Testable => 0u8,
            LeadStatus::Contested => 1,
            LeadStatus::Open => 2,
            LeadStatus::Settled => 3,
        };
        let mut out = leads.to_vec();
        out.sort_by(|a, b| {
            group(a.status)
                .cmp(&group(b.status))
                .then(self.score(b).cmp(&self.score(a)))
        });
        out
    }

    /// Learn from one investigation of `lead`, reported by `source`.
    ///
    /// # Errors
    /// [`LearnRefusal::StaleTable`] when `step` was prepared for another spec.
    pub fn learn(
        &mut self,
        step: &PreparedStep,
        lead: &Lead,
        outcome: Outcome,
        source: u32,
    ) -> Result<Learned, LearnRefusal> {
        if step.spec != self.spec {
            return Err(LearnRefusal::StaleTable {
                table: step.spec,
                model: self.spec,
            });
        }
        if !self.seen.insert(source) {
            return Ok(Learned::Replayed);
        }
        let target = match outcome {
            Outcome::Hydrated => TARGET,
            Outcome::Refuted => -TARGET,
        };
        let residual = target - self.predict(lead);
        let x = features(lead);

        // Signed deltas in code space, no float and no rounding:
        // M = |r|·x / 255 truncated, P = present AND (positive OR M == 0).
        // An absent feature is P=0, M=0 (never touched) and lut9 keeps it so.
        let (mut mags, mut present, mut zero) = ([0u8; FEATURES], 0u64, 0u64);
        for (i, &xi) in x.iter().enumerate() {
            if xi == 0 {
                continue;
            }
            present |= 1 << i;
            let m = (u32::from(residual.unsigned_abs()) * u32::from(xi)) / u32::from(FEATURE_SCALE);
            mags[i] = m.min(255) as u8;
            zero |= u64::from(mags[i] == 0) << i;
        }
        let positive = if residual >= 0 { present } else { 0 };
        let pres = [present & (positive | zero)];
        // η · delta through the odd table.
        let mut out = [0u8; FEATURES];
        let mut out_pres = [0u64; 1];
        lut9(&mags, &pres, &step.table, &mut out, &mut out_pres);

        for (i, w) in self.weights.iter_mut().enumerate() {
            let code = u16::from(out[i]) | (((out_pres[0] >> i) & 1) as u16) << 8;
            let Some(s) = EpiLane9::from_codeword(code).and_then(EpiLane9::value) else {
                continue; // feature absent: weight untouched
            };
            *w = lane((w.value().unwrap_or(0) + s).clamp(-255, 255));
        }
        Ok(Learned::Updated { residual })
    }
}

