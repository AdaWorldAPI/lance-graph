    fn fixed_lead(conf: f32, freq: f32) -> Lead {
        Lead {
            mediator: 1,
            first: Link {
                truth: Some(TruthValue::new(freq, conf)),
                in_chain: true,
            },
            second: Link {
                truth: None,
                in_chain: false,
            },
            hydration: Hydration::Partial,
            status: LeadStatus::Testable,
            uncertainty: 1.0,
        }
    }

