#!/usr/bin/env python3
"""Generate `.claude/board/FRUITS.md`: the open fruits across the board ledgers.

WHY GENERATED
-------------
A fruit is a ledger row that a session could pick up. Kept by hand, the list
drifts from the ledgers it summarises, and the gap between the two is where a
ball gets dropped. So the list is COMPUTED from the ledgers, and CI fails when
the committed file is stale (`--check`).

WHAT COUNTS AS A FRUIT
----------------------
Admission is EXPLICIT: a section (a markdown heading and the lines up to the
next heading) is a fruit only if it carries a `**Fruit:**` line naming one
tier, `Low-hanging` | `High-signal` | `Heavy`. A row without that line is not
guessed into the list. The ledgers hold over 4 000 lines of mixed formats and
a heuristic would fire on everything. Tagging a row is the act of admission.

A fruit whose section `**Status:**` reads as terminal (Resolved, Paid,
Implemented, Wontfix, Moot, Superseded, KILLED, PROMOTED, STALLED, Done,
Rejected) is listed as closed, not open. STALLED is terminal for TORQUE only:
the row moved back to IDEAS, and that IDEAS row is where the fruit now lives.

KIND COMES FROM THE LEDGER, NOT FROM THE ROW
--------------------------------------------
    TORQUE.md     -> discovery torque   (being moved now)
    IDEAS.md      -> innovation debt    (named, not yet moved)
    TECH_DEBT.md  -> engineering debt   (deferred on purpose)
    ISSUES.md     -> blocker            (broken or stuck)

Keeping the kind separate is the point: a high-signal idea and a lint fix are
different balls, and they are never shown in one queue.

USAGE
-----
    python3 .claude/tools/fruits_index.py            # print to stdout
    python3 .claude/tools/fruits_index.py --write    # rewrite FRUITS.md
    python3 .claude/tools/fruits_index.py --check    # exit 1 if FRUITS.md is stale
    python3 .claude/tools/fruits_index.py --self-test
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
BOARD = ROOT / ".claude" / "board"
OUT = BOARD / "FRUITS.md"

LEDGERS = (
    ("TORQUE.md", "discovery torque"),
    ("IDEAS.md", "innovation debt"),
    ("TECH_DEBT.md", "engineering debt"),
    ("ISSUES.md", "blocker"),
)
TIERS = ("High-signal", "Low-hanging", "Heavy")
TERMINAL = re.compile(
    r"\b(resolved|paid|implemented|wontfix|moot|superseded|killed|promoted|stalled|done|rejected)\b",
    re.IGNORECASE,
)
HEADING = re.compile(r"^(#{2,4})\s+(.*\S)\s*$")
FRUIT = re.compile(r"^\*\*Fruit:\*\*\s*(\S+)")
STATUS = re.compile(r"^\*\*Status:\*\*\s*(.*\S)")


class FruitError(ValueError):
    pass


def sections(text: str):
    """Yield (title, body_lines) for each heading-delimited section."""
    title, body = None, []
    for line in text.splitlines():
        m = HEADING.match(line)
        if m:
            if title is not None:
                yield title, body
            title, body = m.group(2), []
        elif title is not None:
            body.append(line)
    if title is not None:
        yield title, body


def fruits_in(name: str, kind: str, text: str):
    out = []
    for title, body in sections(text):
        tier = status = None
        for line in body:
            if tier is None and (m := FRUIT.match(line.strip())):
                tier = m.group(1)
            if status is None and (m := STATUS.match(line.strip())):
                status = m.group(1)
        if tier is None:
            continue
        if tier not in TIERS:
            raise FruitError(f"{name}: '{title}': unknown fruit tier {tier!r} (want one of {TIERS})")
        closed = bool(status and TERMINAL.search(status))
        out.append(
            {"ledger": name, "kind": kind, "title": title, "tier": tier,
             "status": status or "—", "closed": closed}
        )
    return out


def collect(board: pathlib.Path = BOARD):
    rows = []
    for name, kind in LEDGERS:
        path = board / name
        if path.exists():
            rows.extend(fruits_in(name, kind, path.read_text(encoding="utf-8")))
    return rows


def esc(s: str) -> str:
    return s.replace("|", "\\|")


def render(rows) -> str:
    open_rows = [r for r in rows if not r["closed"]]
    closed_rows = [r for r in rows if r["closed"]]
    lines = [
        "# Fruits: open work across the board ledgers",
        "",
        "Generated by `.claude/tools/fruits_index.py --write`. Do not hand-edit:",
        "add or change a `**Fruit:**` line on the ledger row and regenerate.",
        "CI fails when this file is stale.",
        "",
        f"Open: {len(open_rows)}. Closed: {len(closed_rows)}.",
        "",
    ]
    for _, kind in LEDGERS:
        group = [r for r in open_rows if r["kind"] == kind]
        lines.append(f"## {kind}")
        lines.append("")
        if not group:
            lines.append("_none open_")
            lines.append("")
            continue
        lines.append("| tier | row | status | ledger |")
        lines.append("|---|---|---|---|")
        for tier in TIERS:
            for r in group:
                if r["tier"] == tier:
                    lines.append(f"| {tier} | {esc(r['title'])} | {esc(r['status'])} | `{r['ledger']}` |")
        lines.append("")
    if closed_rows:
        lines.append("## closed (kept for traceability)")
        lines.append("")
        lines.append("| tier | row | status | ledger |")
        lines.append("|---|---|---|---|")
        for r in closed_rows:
            lines.append(f"| {r['tier']} | {esc(r['title'])} | {esc(r['status'])} | `{r['ledger']}` |")
        lines.append("")
    return "\n".join(lines)


def self_test() -> int:
    text = """# L
## a — tagged open
**Fruit:** High-signal
**Status:** TORQUE
## b — untagged
**Status:** Open
## c — tagged closed
**Fruit:** Heavy
**Status:** Paid (#12)
## d — tagged, no status
**Fruit:** Low-hanging
"""
    rows = fruits_in("X.md", "k", text)
    titles = [r["title"] for r in rows]
    # Can fire: tagged rows are admitted.
    assert titles == ["a — tagged open", "c — tagged closed", "d — tagged, no status"], titles
    # Can stay silent: an untagged row is never guessed in.
    assert "b — untagged" not in titles
    # Terminal status closes a fruit; a live one stays open.
    by = {r["title"]: r for r in rows}
    assert by["c — tagged closed"]["closed"] and not by["a — tagged open"]["closed"]
    assert not by["d — tagged, no status"]["closed"]
    # An unknown tier is an error, not a silent drop.
    try:
        fruits_in("X.md", "k", "## z\n**Fruit:** Medium\n")
    except FruitError:
        pass
    else:
        raise AssertionError("unknown tier was accepted")
    # Rendering keeps open and closed apart.
    out = render(rows)
    assert "Open: 2. Closed: 1." in out, out
    print("fruits_index self-test: OK")
    return 0


def main(argv) -> int:
    if "--self-test" in argv:
        return self_test()
    out = render(collect())
    if "--write" in argv:
        OUT.write_text(out + "\n", encoding="utf-8")
        return 0
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != out + "\n":
            print("FRUITS.md is stale. Run: python3 .claude/tools/fruits_index.py --write", file=sys.stderr)
            return 1
        return 0
    print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
