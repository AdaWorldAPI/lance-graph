#!/usr/bin/env python3
"""Generate `crates/lance-graph-contract/src/qualia_profile_table.rs` from
`data/qualia/calibrated_219.json`.

Deterministic: entries are emitted sorted by `id`; palette index = position + 1
(index 0 is reserved for UNNAMED). The PCS vector is stored as `[i8; 17]` in
hundredths — the calibration set is specified to 0.05 granularity, so the
round trip is exact. Two fingerprints are emitted so the generated table can
be checked against its source without a JSON parser in the zero-dep crate:

  PROFILE_ID  — sha256 of the source JSON bytes (ICC "profile ID" field)
  TABLE_FNV   — FNV-1a 64 over the emitted (id, pcs) bytes, re-computable in Rust

Run from the repo root:  python3 scripts/gen_qualia_profile.py
"""
import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "qualia" / "calibrated_219.json"
DST = ROOT / "crates" / "lance-graph-contract" / "src" / "qualia_profile_table.rs"

PCS_AXES = [
    "valence", "arousal", "dominance", "warmth", "brightness", "tension",
    "clarity", "social", "nostalgia", "sacredness", "desire", "grief", "awe",
    "shame", "hope", "edge", "resolution_hunger",
]


def rs(s: str) -> str:
    """Quote a Python string as a Rust string literal (UTF-8 kept verbatim)."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def fnv1a64(data: bytes) -> int:
    h = 0xCBF29CE484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main() -> int:
    raw = SRC.read_bytes()
    doc = json.loads(raw)
    if doc["axes_17d"] != PCS_AXES:
        print("axis order in JSON does not match PCS_AXES", file=sys.stderr)
        return 1
    entries = sorted(doc["entries"], key=lambda e: e["id"])
    ids = [e["id"] for e in entries]
    if len(set(ids)) != len(ids):
        print("duplicate ids", file=sys.stderr)
        return 1
    if len(entries) > 219:
        print("more than 219 entries: palette slots 220..255 are reserved", file=sys.stderr)
        return 1

    profile_id = hashlib.sha256(raw).hexdigest()
    fnv_bytes = bytearray()
    rows = []
    for pos, e in enumerate(entries):
        pcs = []
        for ax in PCS_AXES:
            v = e["vector_17d"][ax]
            q = round(v * 100)
            if abs(v * 100 - q) > 1e-6 or not -128 <= q <= 127:
                print(f"{e['id']}: {ax}={v} is not representable in i8 hundredths", file=sys.stderr)
                return 1
            pcs.append(q)
        fnv_bytes += e["id"].encode()
        fnv_bytes += bytes((q & 0xFF) for q in pcs)
        tags = ", ".join(rs(t) for t in e.get("qualia_tags", []))
        rows.append(
            "    NamedQualia {\n"
            f"        idx: {pos + 1},\n"
            f"        id: {rs(e['id'])},\n"
            f"        label: {rs(e['label'])},\n"
            f"        family: {rs(e['family'])},\n"
            f"        subfamily: {rs(e.get('subfamily', ''))},\n"
            f"        pcs: [{', '.join(str(q) for q in pcs)}],\n"
            f"        tags: &[{tags}],\n"
            "    },"
        )
    table_fnv = fnv1a64(bytes(fnv_bytes))

    out = [
        "// GENERATED by scripts/gen_qualia_profile.py from data/qualia/calibrated_219.json",
        "// Do not hand-edit. Re-run the script; `qualia_profile::tests::table_fnv_matches_source`",
        "// fails if this file and the source disagree.",
        "",
        "use super::qualia_profile::NamedQualia;",
        "",
        f"/// sha256 of `data/qualia/calibrated_219.json` (the ICC profile-ID field).",
        f'pub const PROFILE_ID: &str = "{profile_id}";',
        "",
        "/// FNV-1a 64 over `id` bytes ++ `pcs` bytes of every row, in table order.",
        f"pub const TABLE_FNV: u64 = 0x{table_fnv:016X};",
        "",
        f"/// Number of named qualia. Palette index 0 = UNNAMED; 1..={len(entries)} = this table;",
        f"/// {len(entries) + 1}..=255 reserved (RESERVE-DON'T-RECLAIM).",
        f"pub const NAMED_COUNT: usize = {len(entries)};",
        "",
        f"pub static NAMED: [NamedQualia; {len(entries)}] = [",
        *rows,
        "];",
        "",
    ]
    DST.write_text("\n".join(out), encoding="utf-8")
    # keep the committed file rustfmt-stable so `cargo fmt --check` and this script agree
    import shutil
    import subprocess
    if shutil.which("rustfmt"):
        subprocess.run(["rustfmt", "--edition", "2021", str(DST)], check=True)
    print(f"wrote {DST.relative_to(ROOT)}: {len(entries)} rows, PROFILE_ID={profile_id[:12]}…, TABLE_FNV=0x{table_fnv:016X}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
